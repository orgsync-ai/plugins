// @ts-check
// D-195 capture, step 1 (plan B2 §4.5 step 4): the text an extractor may read. It keeps what the person and the assistant wrote and
// drops everything else: tool results and tool inputs (a tool's name may stay, as `[tool: Name]`), thinking, attachments, images,
// system reminders and injected context, `_meta` and `mcpMeta` (spike S1: Claude Code stores result `_meta` there, card tokens
// included), compaction summaries and subagent turns. Dropping tool results is the main defence against prompt injection as well
// as the main size cut. Secrets are masked. An unknown transcript format is refused, never guessed.
import { CREDENTIAL_PATTERNS, LOCAL_SECRET_PATTERNS, MASK } from "./gate.js";
import { utf8Length } from "./sha256.js";

/** Masks credential shapes and Luhn-valid card numbers with `[secret]`. @param {string} text */
export function maskSecrets(text) {
  let masked = text;
  for (const pattern of [...CREDENTIAL_PATTERNS, ...LOCAL_SECRET_PATTERNS]) masked = masked.replace(new RegExp(pattern.source, pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`), MASK);
  return masked.replace(/\b\d(?:[ -]?\d){12,18}\b/g, run => luhn(run.replace(/\D/g, "")) ? MASK : run);
}

/** @param {string} digits */
function luhn(digits) {
  let sum = 0;
  for (let index = 0; index < digits.length; index += 1) {
    let digit = Number(digits[digits.length - 1 - index]);
    if (index % 2 === 1) { digit *= 2; if (digit > 9) digit -= 9; }
    sum += digit;
  }
  return sum % 10 === 0;
}

// Blocks the app injects into a turn's text: what a command printed, reminders, hook context, environment and instructions files.
const DROPPED_BLOCKS = /<(system-reminder|local-command-stdout|local-command-stderr|bash-stdout|bash-stderr|bash-input|command-stdout|command-stderr|task-notification|user-prompt-submit-hook|environment_context|user_instructions|user_shell_command|turn_aborted|INSTRUCTIONS|ide_selection|ide_opened_file)\b[^>]*>[\s\S]*?<\/\1>/g;
const COMMAND_TAGS = /<(command-name|command-message|command-args)>([\s\S]*?)<\/\1>/g;
/** Turns that are the app's own text rather than the person's: compaction summaries, interruption notes, instructions files, a
 * skill's text when a command loads it, and what OrgSync's own mod adds (the picture, change notes, the steering digest). */
const APP_TURN = /^(This session is being continued from a previous conversation|Caveat: The messages below were generated by the user while running local commands|\[Request interrupted by user|# AGENTS\.md instructions for |<environment_context>|<user_instructions>|Base directory for this skill: |OrgSync picture, as of |OrgSync changes, company data|Changed since your last session, company data)/;

/** A turn's own words, with injected blocks and secrets removed. @param {string} text */
export function turnText(text) {
  const kept = text.replace(DROPPED_BLOCKS, " ").replace(COMMAND_TAGS, (_, tag, inner) => tag === "command-name" ? String(inner).trim() : tag === "command-args" ? ` ${String(inner).trim()}` : "")
    .replace(/<[a-z_-]+-(stdout|stderr|output|result)>[\s\S]*$/i, " ").trim();
  return APP_TURN.test(kept) ? "" : maskSecrets(kept);
}

/** @param {"user" | "assistant"} role @param {string} text @param {readonly string[]} tools */
const line = (role, text, tools) => `${role === "user" ? "Person" : "Assistant"}: ${[text, ...tools.map(name => `[tool: ${name}]`)].filter(Boolean).join(" ")}`;
/** A tool's name as it may be shown: letters, digits and a few separators, at most 80 characters. @param {unknown} name */
const toolName = name => typeof name === "string" && /^[A-Za-z0-9_.:-]{1,80}$/.test(name) ? name : "tool";

/** @typedef {{ role?: unknown, text?: unknown, toolUses?: unknown, toolResults?: unknown }} SessionMessage */

/**
 * The Claude Code mod's `$.session.messages()` entries as an extractor may read them: each person and assistant turn's text, tool
 * names only. `toolUses` inputs and results and every `toolResults` entry are never read.
 * @param {readonly SessionMessage[]} messages @returns {{ text: string, turns: number }}
 */
export function redactMessages(messages) {
  /** @type {string[]} */
  const lines = [];
  for (const message of messages) {
    if (message === null || typeof message !== "object" || (message.role !== "user" && message.role !== "assistant")) continue;
    const text = typeof message.text === "string" ? turnText(message.text) : "";
    const tools = message.role === "assistant" && Array.isArray(message.toolUses)
      ? message.toolUses.map(use => toolName(use !== null && typeof use === "object" ? /** @type {Record<string, unknown>} */ (use).tool : null)) : [];
    if (text || tools.length) lines.push(line(message.role, text, tools));
  }
  return { text: lines.join("\n\n"), turns: lines.length };
}

/** @param {unknown} value @returns {Record<string, unknown> | null} */
const object = value => value !== null && typeof value === "object" && !Array.isArray(value) ? /** @type {Record<string, unknown>} */ (value) : null;

/** @typedef {{ text: string, format: string, nextOffset: number } | { text: null, format: null }} Redacted */
const UNKNOWN = Object.freeze({ text: null, format: null });

/**
 * Complete lines at or after a UTF-8 byte offset, each with the offset just past it. A last line without its newline is still
 * being written and waits for the next run.
 * @param {string} text @param {number} fromOffset
 */
function linesFrom(text, fromOffset) {
  /** @type {{ value: Record<string, unknown> | null, end: number }[]} */
  const lines = [];
  let offset = 0, start = 0;
  for (let newline = text.indexOf("\n"); newline >= 0; newline = text.indexOf("\n", start)) {
    const raw = text.slice(start, newline), end = offset + utf8Length(raw) + 1;
    if (offset >= fromOffset && raw.trim()) {
      /** @type {Record<string, unknown> | null} */
      let value = null;
      try { value = object(JSON.parse(raw)); } catch { value = null; }
      lines.push({ value, end });
    }
    offset = end; start = newline + 1;
  }
  return { lines, end: Math.max(offset, fromOffset) };
}

const CLAUDE_CODE_TYPES = new Set(["user", "assistant", "system", "summary", "attachment", "file-history-snapshot", "queue-operation", "progress", "custom-title"]);
const CODEX_TYPES = new Set(["session_meta", "response_item", "event_msg", "turn_context", "compacted"]);

/**
 * A Claude Code session file (JSONL) from a byte offset: person and assistant text blocks only. Tool results, thinking, images,
 * documents, attachments, `toolUseResult`, `mcpMeta` and every `_meta` are never read, nor are meta, compaction and subagent turns.
 * @param {string} text @param {number} [fromOffset] @returns {Redacted}
 */
export function redactClaudeCodeJsonl(text, fromOffset = 0) {
  const { lines, end } = linesFrom(text, fromOffset);
  /** @type {string[]} */
  const out = [];
  let known = lines.length === 0;
  for (const { value } of lines) {
    if (!value || typeof value.type !== "string" || CODEX_TYPES.has(value.type)) return UNKNOWN;
    if (!CLAUDE_CODE_TYPES.has(value.type)) continue;
    known = true;
    if (value.type !== "user" && value.type !== "assistant") continue;
    const message = object(value.message);
    if (!message || message.role !== value.type || (typeof message.content !== "string" && !Array.isArray(message.content))) return UNKNOWN;
    if (value.isMeta === true || value.isCompactSummary === true || value.isSidechain === true || value.isVisibleInTranscriptOnly === true) continue;
    /** @type {string[]} */
    const texts = [], tools = [];
    if (typeof message.content === "string") texts.push(message.content);
    else for (const block of message.content) {
      const part = object(block);
      if (part?.type === "text" && typeof part.text === "string") texts.push(part.text);
      else if (part?.type === "tool_use" && value.type === "assistant") tools.push(toolName(part.name));
    }
    const kept = turnText(texts.join("\n"));
    if (kept || tools.length) out.push(line(value.type, kept, tools));
  }
  return known ? { text: out.join("\n\n"), format: "claude_code_jsonl", nextOffset: end } : UNKNOWN;
}

/**
 * A Codex rollout file (JSONL) from a byte offset: `response_item` messages of the person (`input_text`) and the assistant
 * (`output_text`) only. Reasoning, function and tool calls and their outputs, event messages, environment context and
 * instructions are never read; a call's name may stay.
 * @param {string} text @param {number} [fromOffset] @returns {Redacted}
 */
export function redactCodexJsonl(text, fromOffset = 0) {
  const { lines, end } = linesFrom(text, fromOffset);
  /** @type {string[]} */
  const out = [];
  let known = lines.length === 0;
  for (const { value } of lines) {
    if (!value || typeof value.type !== "string" || value.type === "user" || value.type === "assistant") return UNKNOWN;
    if (!CODEX_TYPES.has(value.type)) continue;
    known = true;
    if (value.type !== "response_item") continue;
    const payload = object(value.payload);
    if (!payload || typeof payload.type !== "string") return UNKNOWN;
    if (payload.type === "function_call" || payload.type === "custom_tool_call" || payload.type === "local_shell_call" || payload.type === "web_search_call") {
      const previous = out.at(-1);
      const name = `[tool: ${toolName(payload.type === "local_shell_call" ? "shell" : payload.type === "web_search_call" ? "web_search" : payload.name)}]`;
      if (previous?.startsWith("Assistant: ")) out[out.length - 1] = `${previous} ${name}`;
      else out.push(`Assistant: ${name}`);
      continue;
    }
    if (payload.type !== "message") continue;
    if (payload.role !== "user" && payload.role !== "assistant") continue;
    if (!Array.isArray(payload.content)) return UNKNOWN;
    const wanted = payload.role === "user" ? "input_text" : "output_text";
    const texts = payload.content.map(object).filter(part => part?.type === wanted && typeof part.text === "string").map(part => String(part?.text));
    const kept = turnText(texts.join("\n"));
    if (kept) out.push(line(payload.role, kept, []));
  }
  return known ? { text: out.join("\n\n"), format: "codex_rollout_jsonl", nextOffset: end } : UNKNOWN;
}
